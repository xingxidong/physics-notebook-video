def measure(obj,size):
    if isinstance(obj,str):
        return sum((.24 if c==' ' else glyphs[c][0] if c in glyphs else 1.06)*size for c in obj)
    kind,*args=obj
    if kind=='row': return sum(measure(a,size) for a in args)
    if kind=='frac': return max(measure(a,size*.78) for a in args)+size*.25
    if kind in ('sup','sub'): return measure(args[0],size)+measure(args[1],size*.58)
    if kind in ('vec','hat','dot'): return measure(args[0],size)
    if kind=='sqrt': return measure(args[0],size)+size*.55
    raise ValueError(obj)

def vertical_bounds(obj,size):
    if isinstance(obj,str):
        points=[v*size for c in obj if c!=' ' for path in glyphs.get(c,(1,[[[0,0],[1,1]]]))[1] for u,v in path]
        return (min(points),max(points)) if points else (0,0)
    kind,*a=obj
    if kind=='row':
        b=[vertical_bounds(v,size) for v in a];return (min((v[0] for v in b),default=0),max((v[1] for v in b),default=0))
    if kind=='frac':
        bn=vertical_bounds(a[0],size*.78);bd=vertical_bounds(a[1],size*.78);ny=size*.43-size*.14-bn[1];dy=size*.43+size*.14-bd[0];return ny+bn[0],dy+bd[1]
    if kind in ('sub','sup'):
        b=vertical_bounds(a[0],size);c=vertical_bounds(a[1],size*.58);dy=size*(.48 if kind=='sub' else -.37);return min(b[0],c[0]+dy),max(b[1],c[1]+dy)
    b=vertical_bounds(a[0],size)
    if kind=='sqrt':return b[0]-.12*size,b[1]
    if kind in ('hat','vec','dot'):return min(b[0],-.3*size),b[1]
    raise ValueError(obj)

def formula(group,obj,x,y,size=34,color=BLUE):
    if isinstance(obj,str): return text(group,obj,x,y,size,color)
    kind,*args=obj; w=measure(obj,size)
    if kind=='row':
        for a in args: x=formula(group,a,x,y,size,color)
        return x
    if kind=='frac':
        bn=vertical_bounds(args[0],size*.78);bd=vertical_bounds(args[1],size*.78)
        for a,dy in zip(args,[size*.43-size*.14-bn[1],size*.43+size*.14-bd[0]]):
            aw=measure(a,size*.78); formula(group,a,x+(w-aw)/2,y+dy,size*.78,color)
        line(group,(x,y+size*.43),(x+w,y+size*.43),color,2.2)
    elif kind in ('sup','sub'):
        dx=measure(args[0],size);formula(group,args[0],x,y,size,color)
        formula(group,args[1],x+dx,y+size*(-.37 if kind=='sup' else .48),size*.58,color)
    elif kind in ('vec','hat','dot'):
        formula(group,args[0],x,y,size,color)
        if kind=='vec': arrow(group,(x,y-size*.10),(x+w,y-size*.10),color,1.8)
        elif kind=='hat': stroke(group,[[x,y],[x+w/2,y-size*.15],[x+w,y]],color,1.8)
        else: stroke(group,[[x+w*.5,y-size*.14],[x+w*.5+.01,y-size*.14]],color,3)
    elif kind=='sqrt':
        top=vertical_bounds(args[0],size)[0]-.12*size
        stroke(group,[[x,y+size*.50],[x+size*.14,y+size*.72],[x+size*.36,y+top],[x+w,y+top]],color,2)
        formula(group,args[0],x+size*.55,y,size,color)
    return x+w

def ellipse(group,c,rx,ry=None,color=INK,width=2.6):
    ry=rx if ry is None else ry
    stroke(group,[[c[0]+rx*math.cos(t),c[1]+ry*math.sin(t)] for t in [i*math.tau/100 for i in range(101)]],color,width)

def circle_dashed(group,c,r,color=BLUE):
    for j in range(24):
        stroke(group,[[c[0]+r*math.cos(t),c[1]+r*math.sin(t)] for t in [(j+k/8*.55)*math.tau/24 for k in range(9)]],color,2)

def charge(group,c,label='q',size=28,color=RED):
    ellipse(group,c,9,color=color,width=2)
    line(group,(c[0]-4,c[1]),(c[0]+4,c[1]),color,1.8)
    line(group,(c[0],c[1]-4),(c[0],c[1]+4),color,1.8)
    text(group,label,c[0]+14,c[1]+2,size,color)

