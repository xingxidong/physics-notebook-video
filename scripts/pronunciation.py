def spoken_symbols(text):
    units = [m.span() for pattern in (MEASUREMENT, UNIT_RATIO) for m in pattern.finditer(text)]
    matches = [m for m in FREE_SYMBOL.finditer(text) if not any(a <= m.start() < b for a, b in units)]
    for label in GEOMETRY_LABEL.finditer(text):
        matches.extend(CAPITAL.finditer(text, *label.span(1)))
    return sorted(matches, key=lambda m: m.start())


def symbol_reading(symbol):
    upper = symbol.upper()
    if upper in LETTER_IPA:
        return f'{upper} /{LETTER_IPA[upper]}/'
    return GREEK.get(symbol.lower(), symbol)


def letter_bindings(text, requested=None):
    if requested is None:
        requested = {}
    if not isinstance(requested, dict) or any(
        not isinstance(k, str) or not FREE_SYMBOL.fullmatch(k) or not isinstance(v, str) or not v.strip()
        for k, v in requested.items()
    ):
        raise ValueError('symbol_readings 应填单个字母和字母名。')
    symbols = {m.group() for m in spoken_symbols(text)}
    absent = requested.keys() - symbols - {m.group() for m in FREE_SYMBOL.finditer(text)}
    if absent:
        raise ValueError(f'句中找不到独立变量符号 {sorted(absent)}。')
    result = {}
    for symbol in symbols:
        upper = symbol.upper()
        default = ENGLISH_NAMES.get(upper, upper) if upper in LETTER_IPA else symbol_reading(symbol)
        result[symbol] = default
    return result


def resolve_readings(text, readings=None):
    names = letter_bindings(text, readings)
    pieces = []
    last = 0
    for m in spoken_symbols(text):
        name = names[m.group()]
        if name.isascii():
            left = ' ' if m.start() and text[m.start()-1].isalnum() and not (pieces and pieces[-1].endswith(' ')) else ''
            right = ' ' if m.end() < len(text) and text[m.end()].isalnum() else ''
            name = left + name + right
        pieces.extend([text[last:m.start()], name])
        last = m.end()
    return ''.join([*pieces, text[last:]])


def display_words(text, readings, words):
    """Keep provider timing at whole-word boundaries outside a spoken alias."""
    if not readings or not words:
        return words
    clean = lambda value: ''.join(c.lower() for c in value if c.isalnum())
    boundaries = {0: 0}
    printed = []
    spoken = []
    offset = 0
    last = 0

    def append(unit, reading):
        nonlocal offset
        printed.append(unit)
        spoken.append(reading)
        offset += len(reading)
        boundaries[offset] = len(printed)

    for match in spoken_symbols(text):
        if match.group() not in readings:
            continue
        for char in text[last:match.start()]:
            if char.isalnum():
                append(char, char.lower())
        append(match.group(), clean(readings[match.group()]))
        last = match.end()
    for char in text[last:]:
        if char.isalnum():
            append(char, char.lower())
    if ''.join(spoken) != ''.join(clean(w['text']) for w in words):
        return []
    result = []
    consumed = start_index = 0
    start_time = None
    for word in words:
        token = clean(word['text'])
        if not token:
            continue
        if start_time is None:
            start_time = word['start']
        consumed += len(token)
        if consumed in boundaries:
            end = boundaries[consumed]
            result.append({'text': ''.join(printed[start_index:end]), 'start': start_time, 'end': word['end']})
            start_index, start_time = end, None
    return result


def reference_readings():
    from feedback_bank import catalog
    terms = {k:v for k,v in PHYSICS_TERMS.items() if k in PHYSICS_PINYIN or SUBJECT_POLYPHONES.intersection(k)}
    from classroom_terms import ARCHIVE, saved_cards, feedback_cards
    for term, card in saved_cards(ARCHIVE).items():
        sounds = card['readings']
        if len(sounds) == 1 and sounds[0]:
            terms.setdefault(term, sounds[0])
    for term, card in feedback_cards().items():
        if card.get('feedback_reading'):
            terms[term] = card['feedback_reading']
    for key, entry in catalog()['polyphones'].items():
        if entry.get('context_required'):
            terms.pop(key, None)
        elif entry.get('expected'):
            terms[key] = entry['expected']
    return terms


def matched_pronunciations(text, course_overrides=None, cue_overrides=None):
    """Use standard readings and viewer corrections, then course and cue overrides."""
    terms = reference_readings()
    for overrides in (course_overrides, cue_overrides):
        if overrides is None:
            continue
        if overrides is False:
            terms.clear()
            continue
        if not isinstance(overrides, dict):
            raise ValueError('minimax_pronunciation must be a mapping of Chinese terms to numbered pinyin, or false')
        for term, pinyin in overrides.items():
            if not isinstance(term, str) or not HAN_TERM.fullmatch(term):
                raise ValueError(f'Pronunciation term must contain Chinese characters: {term!r}')
            if pinyin is None:
                terms.pop(term, None)
                continue
            syllables = pinyin.lower().split() if isinstance(pinyin, str) else []
            if len(syllables) != len(term) or not all(SYLLABLE.fullmatch(s) for s in syllables):
                raise ValueError(f'{term}: provide one pinyin syllable with a tone number 1–5 per character')
            terms[term] = ' '.join(syllables)
    return {m.group(): terms[m.group()] for m in term_pattern(terms).finditer(text)} if terms else {}


def term_pattern(terms):
    return _compiled_term_pattern(tuple(sorted(terms, key=lambda t: (-len(t), t))))


@lru_cache(maxsize=4096)
def _compiled_term_pattern(ordered):
    choices = []
    for term in ordered:
        pattern = re.escape(term)
        if term in ('同相', '反相'):
            pattern += '(?!干|位|乘|除)'
        if term == '测量':
            # In 预测量子态 and 探测量子态 the word boundary falls before 量子.
            pattern = r'(?:(?<![预探])测量|测量(?!子))'
        if term == '相交':
            # 三相 / 交流电 has xiàng. 两直线相交 and 三相交于一点 have xiāng.
            pattern = r'(?:(?<![单双两二三四五六七八九十多])相交|相交(?!流))'
        if term == '转角':
            # 偏转 / 角 uses zhuǎn within 偏转, unlike a standalone 转角.
            pattern = r'(?<!偏)转角'
        if term == '位矢':
            # 单位 / 矢量 is a unit vector. 位矢 denotes a position vector.
            pattern = r'(?:(?<!单)位矢|位矢(?!量))'
        if term in ('的量', '这个量', '那个量'):
            pattern += r'(?=$|[，。！？、；：,.!?;\s]|是|为|有|等于|叫|随|指)'
        if term == '矩阵的行':
            pattern += r'(?=$|[，。？！、；：,.!?;\s]|和列|与列|数|向量|空间)'
        if term == '似的':
            pattern = r'(?<![相类近])似的'
        if term == '量出':
            pattern += '(?!现)'
        choices.append(pattern)
    return re.compile('|'.join(choices))


# Plain-text local synthesizers have no portable pinyin API. Use same-sound
# characters only for the documented trouble spots and only in the TTS input.
PLAIN_HINTS = {'长度': ('chang2 du4', '常度'), '相位': ('xiang4 wei4', '向位'),
               '相位差': ('xiang4 wei4 cha1', '向位差'), '的量': ('de5 liang4', '的亮')}
PLAIN_HINTS.update({term: (reading, term[:-1] + '亮')
                    for term, reading in PHYSICS_PINYIN.items()
                    if term.endswith('分量') and reading.endswith('fen1 liang4')})


def local_tts_text(text, terms, course=None, cue=None):
    from feedback_bank import catalog
    known = dict(PLAIN_HINTS)
    for key, entry in catalog()['polyphones'].items():
        if entry.get('hint') and entry.get('expected') and not entry.get('context_required'):
            known[key] = (entry['expected'], entry['hint'])
    custom = {}
    liang_hint = True
    for overrides in (course, cue):
        if overrides is None:
            continue
        if overrides is False:
            known.clear()
            custom.clear()
            liang_hint = False
            continue
        if not isinstance(overrides, dict):
            raise ValueError('plain_pronunciation 应填原词与同音提示的对应表。')
        for term, hint in overrides.items():
            if not isinstance(term, str) or not HAN_TERM.fullmatch(term):
                raise ValueError(f'原词应使用完整中文词语：{term!r}')
            if hint is None:
                custom[term] = term
            elif isinstance(hint, str) and HAN_TERM.fullmatch(hint) and len(hint) == len(term):
                custom[term] = hint
            else:
                raise ValueError(f'“{term}”的同音提示应与原词汉字数相同。')
    hints = dict(custom)
    parts = term_pattern(known.keys() | custom.keys()) if known or custom else None
    for term, reading in terms.items():
        if term in custom:
            continue
        syllables = reading.split()
        chars = ['梁' if liang_hint and c == '量' and sound == 'liang2' else c for c, sound in zip(term, syllables)]
        # Longer subject terms inherit a heard spelling only where the same
        # syllables carry the same tones. Whole-term matches take precedence.
        for m in parts.finditer(term) if parts else ():
            if m.group() in custom:
                chars[m.start():m.end()] = custom[m.group()]
                continue
            expected, hint = known[m.group()]
            if syllables[m.start():m.end()] == expected.split():
                chars[m.start():m.end()] = hint
        replacement = ''.join(chars)
        if replacement != term:
            hints[term] = replacement
    vocabulary = set(terms) | hints.keys()
    if not vocabulary:
        return text
    return term_pattern(vocabulary).sub(lambda m: hints.get(m.group(), m.group()), text)


def marked_pinyin(syllable):
    """Display numbered pinyin with a tone mark on its standard vowel."""
    sound = syllable[:-1].replace('v', 'ü')
    if syllable[-1] == '5':
        return sound
    vowels = [i for i, c in enumerate(sound) if c in 'aeiouü']
    if not vowels:
        return syllable
    i = next((sound.index(c) for c in ('a', 'e', 'ou') if c in sound), vowels[-1])
    accent = ('\u0304','\u0301','\u030c','\u0300')[int(syllable[-1])-1]
    return unicodedata.normalize('NFC', sound[:i+1] + accent + sound[i+1:])


def tone_targets(text, course_overrides=None, cue_overrides=None, choices=()):
    """Scan by word first. A new use of a risky character remains a context question."""
    from feedback_bank import catalog
    from classroom_terms import context_sense
    selected = {row['offset']+j: sound for row in choices if row.get('reading_source') and
                row.get('expected') and text.startswith(row['term'],row['offset'])
                for j,sound in enumerate(row['expected'].split())}
    remembered = catalog()['polyphones']
    focus = set(SUBJECT_POLYPHONES)
    for entry in remembered.values():
        focus.update(entry.get('focus_chars', entry.get('focus', '')))
    standard = reference_readings()
    configured = matched_pronunciations(text, course_overrides, cue_overrides) if (
        course_overrides is not None or cue_overrides is not None) else {}
    vocabulary = standard.keys() | remembered.keys() | focus | CONTEXT_WORDS
    reference_at = {}
    if configured:
        for m in term_pattern(vocabulary).finditer(text):
            for i, sound in enumerate(standard.get(m.group(), '').split()):
                reference_at[m.start()+i] = (m.group(), sound)
    pattern = term_pattern(vocabulary | configured.keys())
    hits = []
    for match in pattern.finditer(text):
        word = match.group()
        history = any(key in word for key in remembered)
        if not (history or focus.intersection(word) or word in configured):
            continue
        contextual = None
        if word == '分量' and re.search(r'(?:[xyzXYZ](?:\s*轴)?|径向|切向|法向|横向|纵向|波矢|磁矩|场强)\s*(?:的\s*)?$', text[:match.start()]):
            contextual = 'fen1 liang4'
        target = context_sense(word,text,match.start()) or standard.get(word) or contextual or configured.get(word)
        sounds_here = [selected.get(i) for i in range(match.start(),match.end())]
        if all(sounds_here):
            target = ' '.join(sounds_here)
        source = 'context' if not target else 'feedback' if history else 'subject'
        sounds = target.split() if target else []
        configured_sounds = configured.get(word, '').split()
        characters, conflicts = [], []
        for i, char in enumerate(word):
            if char not in focus:
                continue
            offset = match.start() + i
            known_word, expected = reference_at.get(offset, (word, sounds[i] if sounds else None))
            expected = selected.get(offset,expected)
            characters.append({'char': char, 'index': i, 'offset': offset, 'expected': expected,
                               'reading': marked_pinyin(expected) if expected else None})
            if sounds and expected:
                sounds[i] = expected
            if expected and configured_sounds and configured_sounds[i].replace('v','ü') != expected.replace('v','ü'):
                conflicts.append({'word': known_word, 'char': char, 'offset': offset,
                                  'expected': expected, 'configured': configured_sounds[i]})
        hits.append({'term': word, 'offset': match.start(), 'expected': ' '.join(sounds) or None,
                     'reason': source, 'characters': characters, 'conflicts': conflicts})
    return hits


def pronunciation_trial(rows):
    """Select real classroom sentences that cover each term/reading and unfamiliar context."""
    cues = {}
    features = {}
    for row in rows:
        key = (row['page'], row['cue'])
        cue = cues.setdefault(key, {'page': row['page'], 'cue': row['cue'],
                                    'context': row['context'], 'terms': []})
        cue['terms'].append({name: row[name] for name in ('term', 'offset', 'expected', 'reason', 'characters')})
        signs = features.setdefault(key, set())
        for char, syllable in zip(row['term'], (row['expected'] or '').split()):
            if char in SUBJECT_POLYPHONES:
                signs.add(('reading', char, syllable))
        signs.add((row['reason'], row['term'], row['expected']))
    chosen, seen = [], set()
    while features and len(chosen) < 6:
        def score(key):
            fresh = features[key] - seen
            return sum(3 if f[0] in ('feedback','context') else 1 for f in fresh)
        key = max(features, key=score)
        if not score(key):
            break
        chosen.append(cues[key])
        seen.update(features.pop(key))
    return chosen


def minimax_dictionary(matches):
    return {'tone': [term + '/' + ''.join(f'({syllable})' for syllable in pinyin.split())
                     for term, pinyin in matches.items()]}


def classroom_syllables(term, expected, actual):
    """Accept citation tones and ordinary adjacent third-tone sandhi inside a word."""
    wanted, heard = expected.split(), actual.split()
    if len(wanted) != len(term) or len(heard) != len(wanted):
        return [False] * len(term)
    results = []
    for i,(goal,sound) in enumerate(zip(wanted,heard)):
        options = {goal}
        if goal.endswith('3') and i+1 < len(wanted) and wanted[i+1].endswith('3'):
            options.add(goal[:-1]+'2')
        results.append(sound in options)
    return results
